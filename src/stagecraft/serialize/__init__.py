"""Serializer: Hera objects to Helm-compatible YAML templates. See DESIGN.md section 8.

Two kinds of `{{ }}` end up in the output. Argo expressions are escaped so Helm prints them
literally. Helm value references, which arrive as markers from CompileContext.value, become real
Helm expressions; they are spliced in after escaping, so they are never escaped themselves.
"""

import re

import yaml
from hera.workflows import WorkflowTemplate

from stagecraft.context import VALUE_MARKER
from stagecraft.serialize.escape import escape_argo

HEADER = "# Generated by stagecraft. Do not edit: change the pipeline and re-render.\n"

# Placeholders for value references while the YAML is dumped and escaped. Plain alphanumerics,
# so YAML emits them verbatim and escaping leaves them alone.
_TOKEN = re.compile(r"STAGECRAFTVALUE(\d+)(W|S)X")


class _Whole(str):
    """A string that is exactly one value reference: emitted as a whole Helm-quoted value."""


class _Spliced(str):
    """A string with value references inside other text: emitted double-quoted, values spliced
    in with Helm's quoting (whose escapes are valid in a YAML double-quoted scalar) trimmed."""


class _Dumper(yaml.SafeDumper):
    pass


def _represent_str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    # Literal block style keeps scripts readable in review. PyYAML falls back to a quoted
    # style when the string cannot be represented as a block.
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


def _represent_whole(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", str(value), style="")


def _represent_spliced(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", str(value), style='"')


_Dumper.add_representer(str, _represent_str)
_Dumper.add_representer(_Whole, _represent_whole)
_Dumper.add_representer(_Spliced, _represent_spliced)


def serialize(template: WorkflowTemplate) -> str:
    paths: list[str] = []
    data = _tokenize(template.to_dict(), paths)
    text = yaml.dump(
        data,
        Dumper=_Dumper,
        sort_keys=False,
        allow_unicode=True,
        # Never wrap lines: a wrapped Argo expression could not be escaped.
        width=float("inf"),
    )
    return HEADER + _TOKEN.sub(lambda m: _helm_value(paths[int(m[1])], m[2]), escape_argo(text))


def _tokenize(node, paths: list[str]):
    """Replace value markers in every string with tokens, recording each marker's path."""
    match node:
        case dict():
            return {k: _tokenize(v, paths) for k, v in node.items()}
        case list():
            return [_tokenize(v, paths) for v in node]
        case str() if VALUE_MARKER.search(node):
            whole = VALUE_MARKER.fullmatch(node) is not None
            kind = "W" if whole else "S"

            def token(match: re.Match[str]) -> str:
                paths.append(match[1])
                return f"STAGECRAFTVALUE{len(paths) - 1}{kind}X"

            tokenized = VALUE_MARKER.sub(token, node)
            return _Whole(tokenized) if whole else _Spliced(tokenized)
        case _:
            return node


def _helm_value(path: str, kind: str) -> str:
    if kind == "W":
        return f"{{{{ .Values.{path} | quote }}}}"
    return f'{{{{ .Values.{path} | quote | trimPrefix "\\"" | trimSuffix "\\"" }}}}'
