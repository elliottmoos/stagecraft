"""Serializer: Hera objects to Helm-compatible YAML templates. See DESIGN.md section 8."""

import yaml
from hera.workflows import WorkflowTemplate

from stagecraft.serialize.escape import escape_argo

HEADER = "# Generated by stagecraft. Do not edit: change the pipeline and re-render.\n"


class _Dumper(yaml.SafeDumper):
    pass


def _represent_str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    # Literal block style keeps scripts readable in review. PyYAML falls back to a quoted
    # style when the string cannot be represented as a block.
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _represent_str)


def serialize(template: WorkflowTemplate) -> str:
    text = yaml.dump(
        template.to_dict(),
        Dumper=_Dumper,
        sort_keys=False,
        allow_unicode=True,
        # Never wrap lines: a wrapped Argo expression could not be escaped.
        width=float("inf"),
    )
    return HEADER + escape_argo(text)
