"""The generated pipelines chart. See DESIGN.md section 16.

A render produces one self-contained chart: Chart.yaml, a values.schema.json built from every
value reference the pipelines make, and one template file per pipeline. Stagecraft owns exactly
these entries; values come from the release at deploy time.
"""

import json
from collections.abc import Mapping

import yaml

from stagecraft.compile import compile_pipeline, compile_triggers
from stagecraft.context import CompileContext
from stagecraft.serialize import serialize
from stagecraft.spec import Pipeline

# Chart.yaml annotation marking a chart directory as Stagecraft's to replace.
MARKER = "stagecraft/generated"
CHART_FILE = "Chart.yaml"
SCHEMA_FILE = "values.schema.json"
TEMPLATES = "templates"

_JSON_TYPES = {str: "string", int: "integer", float: "number", bool: "boolean"}
_HEADER = "# Generated by stagecraft. Do not edit: change the pipelines and re-render.\n"


def render_chart(pipelines: list[Pipeline], name: str = "pipelines") -> dict[str, str]:
    """The chart's files, by path relative to the chart directory."""
    ctx = CompileContext()
    templates = {
        f"{TEMPLATES}/{p.name}.yaml": serialize(compile_pipeline(p, ctx), *compile_triggers(p, ctx))
        for p in pipelines
    }
    return {
        CHART_FILE: _HEADER + yaml.safe_dump(_chart_metadata(name), sort_keys=False),
        SCHEMA_FILE: json.dumps(values_schema(ctx.references), indent=2) + "\n",
        **templates,
    }


def values_schema(references: Mapping[str, type]) -> dict:
    """A schema requiring every referenced value, with the type it is used as. `global` is
    allowed so the chart also works as a subchart, where Helm passes the parent's globals."""
    root: dict = {}
    for path, kind in references.items():
        *parents, leaf = path.split(".")
        node = root
        for key in parents:
            node = node.setdefault(key, {})
        node[leaf] = kind
    schema = _object(root)
    schema["properties"] = {"global": {"type": "object"}, **schema["properties"]}
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", **schema}


def _object(tree: dict) -> dict:
    keys = sorted(tree)
    return {
        "type": "object",
        "required": keys,
        "properties": {
            k: _object(tree[k]) if isinstance(tree[k], dict) else {"type": _JSON_TYPES[tree[k]]}
            for k in keys
        },
    }


def _chart_metadata(name: str) -> dict:
    return {
        "apiVersion": "v2",
        "name": name,
        "description": "Argo Workflows pipelines rendered by stagecraft",
        "version": "0.0.0",
        "annotations": {MARKER: "true"},
    }
